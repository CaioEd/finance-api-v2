"""Base declarativa do ORM.

A convenção de nomes é decidida aqui, na fase 0, porque renomear constraint
depois de existirem migrations é caro: sem ela, o Postgres inventa nomes e o
autogenerate do Alembic produz `DROP CONSTRAINT` com nome que não existe.
"""

from __future__ import annotations

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
